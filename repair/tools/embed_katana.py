#!/usr/bin/env python3
"""Regenerate the embedded, simplified model from the attributed source GLB."""
from pathlib import Path
from convert_katana import convert
root=Path(__file__).resolve().parents[1]
data=convert((root/'assets/models/cyberpunk-katana.glb').read_bytes())
lines=['// Generated by tools/embed_katana.py; see assets/models/README.md for CC BY 4.0 attribution.',
       '#pragma once','#include <cstdint>','namespace katana_asset {','inline constexpr std::uint8_t data[] = {']
for i in range(0,len(data),20): lines.append(' '+','.join(f'0x{x:02x}' for x in data[i:i+20])+',')
lines+=['};','}']
(root/'src/katana_asset.h').write_text('\n'.join(lines)+'\n',encoding='utf-8')
